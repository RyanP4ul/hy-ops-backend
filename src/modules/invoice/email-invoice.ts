import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import type { InvoiceService } from "./service";
import { minorUnitsToMoney, moneyToMinorUnits } from "../../utils/money";

type Invoice = Awaited<ReturnType<typeof InvoiceService.getInvoiceByOrderId>>;
const money = (value: bigint | null) => value === null ? "Unverified" : `PHP ${minorUnitsToMoney(value)}`;

/** Generate PDF bytes on the server using the same invoice data as Orders. */
export function buildInvoiceAttachment(invoice: Invoice) {
  const subtotal = invoice.items.some(item => item.unit_price === null) ? null : invoice.items.reduce((sum, item) => sum + moneyToMinorUnits(item.unit_price!) * BigInt(item.quantity), 0n);
  const paid = moneyToMinorUnits(invoice.amount_paid);
  const calculatedTotal = subtotal === null ? null : subtotal - moneyToMinorUnits(invoice.discount) + moneyToMinorUnits(invoice.tax) + moneyToMinorUnits(invoice.other_charges);
  const total = calculatedTotal === null ? null : calculatedTotal > 0n ? calculatedTotal : 0n;
  const balance = total === null ? null : total > paid ? total - paid : 0n;
  const doc = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  const margin = 16;
  const right = doc.internal.pageSize.getWidth() - margin;
  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.text("HY COMPANY", margin, 22);
  doc.text("INVOICE", right, 22, { align: "right" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.text("Guiguinto, Bulacan, Philippines", margin, 29);
  const metadata = doc.splitTextToSize([
    `Invoice: ${invoice.invoice_number}`, `Issue date: ${invoice.issue_date}`,
    `Due date: ${invoice.due_date}`, `Status: ${invoice.status}`,
  ].join("\n"), right - margin);
  doc.text(metadata, margin, 40);
  const billTo = [invoice.customer.company_name, invoice.customer.name, invoice.customer.address, invoice.customer.email, invoice.customer.phone].filter(Boolean).join("\n");
  autoTable(doc, {
    startY: 43 + metadata.length * 4,
    margin: { left: margin, right: margin, bottom: 18 },
    head: [["BILL TO", "PAYMENT DETAILS"]],
    body: [[billTo, `Terms: ${invoice.payment_arrangement ?? ""}\nPayment status: ${invoice.payment_status}\nAmount paid: ${money(paid)}\nBalance due: ${money(balance)}`]],
    theme: "plain", styles: { fontSize: 9, cellPadding: 3, overflow: "linebreak" },
    columnStyles: { 0: { cellWidth: 100 } },
  });
  const lastY = () => (doc as jsPDF & { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? 80;
  autoTable(doc, {
    startY: lastY() + 8, margin: { left: margin, right: margin, bottom: 18 },
    head: [["Item", "Description", "Qty", "Unit price", "Amount"]],
    body: invoice.items.map(item => {
      const price = item.unit_price === null ? null : moneyToMinorUnits(item.unit_price);
      return [item.name, item.description ?? "", String(item.quantity), money(price), money(price === null ? null : price * BigInt(item.quantity))];
    }),
    theme: "grid", headStyles: { fillColor: [35, 45, 60] },
    styles: { fontSize: 8, cellPadding: 2.5, overflow: "linebreak" },
    columnStyles: { 0: { cellWidth: 45 }, 1: { cellWidth: 43 }, 2: { halign: "right", cellWidth: 15 }, 3: { halign: "right", cellWidth: 35 }, 4: { halign: "right", cellWidth: 40 } },
  });
  autoTable(doc, {
    startY: lastY() + 8, margin: { left: 110, right: margin, bottom: 18 },
    body: [
      ["Subtotal", money(subtotal)], ["Discount", money(moneyToMinorUnits(invoice.discount))],
      ["Tax", money(moneyToMinorUnits(invoice.tax))], ["Other charges", money(moneyToMinorUnits(invoice.other_charges))],
      ["Total", money(total)], ["Amount paid", money(paid)], ["Balance due", money(balance)],
    ],
    theme: "plain", styles: { fontSize: 9, cellPadding: 2 }, columnStyles: { 1: { halign: "right" } },
  });
  if (invoice.notes) autoTable(doc, {
    startY: lastY() + 8, margin: { left: margin, right: margin, bottom: 18 },
    head: [["Notes"]], body: [[invoice.notes]], theme: "plain", styles: { fontSize: 9, overflow: "linebreak" },
  });
  const pages = doc.getNumberOfPages();
  for (let page = 1; page <= pages; page++) {
    doc.setPage(page);
    doc.setFont("helvetica", "normal"); doc.setFontSize(8); doc.setTextColor(100);
    doc.text("Generated by HYOps", margin, doc.internal.pageSize.getHeight() - 9);
    doc.text(`Page ${page} of ${pages}`, right, doc.internal.pageSize.getHeight() - 9, { align: "right" });
  }
  return {
    filename: `${invoice.invoice_number.replace(/[^a-zA-Z0-9_.-]/g, "_")}.pdf`,
    contentType: "application/pdf",
    content: new Uint8Array(doc.output("arraybuffer")),
  };
}

export async function productSeeds() {
  try {
    await db.transaction(async (tx) => {
      await tx.insert(warehouses).values(warehouse_data);
      await tx.insert(products).values(product_data);
      await tx.insert(product_variants).values(product_variant_data);
      await tx.insert(inventory).values(inventory_data);
    });

    logger.info("Product seed completed successfully.");
  } catch (error) {
    if (error instanceof Error) {
      logger.error("Error seeding database:", error.message);
    }

    throw error;
  }
}
